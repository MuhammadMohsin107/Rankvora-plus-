export type SlotRef = { runId: string; promptId: string; channelId: string; sample: number };

export type AlertSpec = {
  severity: AlertSeverity;
  status: AlertStatus;
  delivery: DeliveryRow[];
  cooldown: string;
  persistence: { rule: string; progress: string } | null;
  handledBy: string | null;
};

export type EventSpec = {
  id: string;
  storeId: string;
  type: EventType;
  runId: string;
  at: string;
  /** Headline id (al-…) when this event raised one of the shared alerts. */
  headlineId: string | null;
  /** Title for events whose alert is not in the shared headline list. */
  title?: string;
  /** Slot-level evidence, resolved from the response generator by the service. */
  previous?: SlotRef;
  current?: SlotRef;
  /** Aggregate evidence the service computes from the run's responses. */
  metric?: "run_incomplete" | "error_spike" | "avg_position" | "competitor_citations" | "integration" | "competitor_named" | "positive_sentiment" | "coverage" | "brand_fact";
  /** Competitor whose named-in-answers rate is compared (metric "competitor_named"). */
  competitor?: string;
  /** Brand fact error: the verified fact, the claim in the answer, and the page it was checked against. */
  fact?: { verified: string; claim: string; source: string; quote: string };
  /** Related Fixes records for the handoff. */
  findingId?: string;
  taskId?: string;
  /** Prompt and provider for aggregate events that point at one slot (brand fact errors). */
  promptId?: string;
  channelId?: string;
  /** For aggregate evidence: the compared runs and the provider (if any). */
  compare?: { previousRunId: string | null; channelId?: string };
  /** Text of the "current" evidence card for connection events. */
  evidenceSummary?: string;
  /** Tone of the "current" evidence card for aggregate events (omitted keeps the older look). */
  currentTone?: "neutral" | "success" | "warning" | "danger" | "info";
  summary: string;
  note?: string;
  alert: AlertSpec | null;
};

